<?php

namespace App\Http\Controllers;

use App\Models\GembaWalk;
use App\Support\WalkReport;
use Barryvdh\DomPDF\Facade\Pdf;
use Illuminate\Foundation\Auth\Access\AuthorizesRequests;
use Illuminate\Support\Str;

class WalkReportPdfController
{
    use AuthorizesRequests;

    /**
     * Stream the gemba walk report as a downloadable PDF.
     */
    public function __invoke(GembaWalk $walk)
    {
        $this->authorize('exportReport', $walk);

        $report = new WalkReport($walk);

        $filename = 'gembawalk-' . Str::slug($walk->title) . '-' . $walk->walked_on->format('Y-m-d') . '.pdf';

        $pdf = Pdf::loadView('reports.walk-pdf', ['report' => $report])
            ->setPaper('a4');

        $pdf->render();
        $dompdf = $pdf->getDomPDF();

        $canvas = $dompdf->getCanvas();
        $font = $dompdf->getFontMetrics()->getFont('DejaVu Sans', 'normal');
        $color = [0.443, 0.443, 0.478]; // #71717a
        $size = 8;
        $y = $canvas->get_height() - 30;

        $canvas->page_text(28, $y, 'Generated by GembaWalk on ' . now()->format('j M Y'), $font, $size, $color);

        $pageText = 'Page {PAGE_NUM} of {PAGE_COUNT}';
        $width = $dompdf->getFontMetrics()->getTextWidth($pageText, $font, $size);
        $canvas->page_text($canvas->get_width() - 28 - $width, $y, $pageText, $font, $size, $color);

        return response($dompdf->output(), 200, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'attachment; filename="' . $filename . '"',
        ]);
    }
}
